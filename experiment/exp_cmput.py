import gymnasium as gym
import minigrid
import numpy as np
import random
import pickle
import matplotlib.pyplot as plt

MAP_SEEDS = [0, 1, 2, 3, 4]

A_RIGHT, A_LEFT, A_FORWARD, A_REFLECT = 0, 1, 2, 3
ACTIONS = [A_RIGHT, A_LEFT, A_FORWARD, A_REFLECT]

# reward function hyperparameters
STEP_COST = -0.01
WALL_PENALTY = -0.10
REFLECT_COST = -0.02

LEARNING_RATE = 0.1
GAMMA = 0.99
EPSILON_START = 1.0
EPSILON_MIN = 0.1
EPSILON_DECAY = 0.995

N_EPISODES = 500
MAX_STEPS = 200
EPSILON_BOOST = 0.8
BOOST_DURATION = 10


def state_to_symbolic(obs):
    return obs["image"].tobytes()


class RewardWrapper(gym.Wrapper):
    def __init__(self, env):
        super().__init__(env)

    def step(self, action):
        base_env = self.env.unwrapped
        obs, reward, terminated, truncated, info = self.env.step(action)
        reward += STEP_COST
        if action == A_FORWARD:
            front_cell = base_env.grid.get(*base_env.front_pos)
            if front_cell is not None and getattr(front_cell, "type", None) == "wall":
                reward += WALL_PENALTY
        return obs, reward, terminated, truncated, info


class ReflectionWrapper(gym.Wrapper):
    def __init__(self, env):
        super().__init__(env)
        self.last_obs = None

    def reset(self, **kwargs):
        obs, info = self.env.reset(**kwargs)
        self.last_obs = obs
        return obs, info

    def step(self, action):
        if action == A_REFLECT:
            obs = self.last_obs
            reward = REFLECT_COST
            terminated = False
            truncated = False
            info = {"reflected": True}
            return obs, reward, terminated, truncated, info
        obs, reward, terminated, truncated, info = self.env.step(action)
        if info is None:
            info = {}
        info["reflected"] = False
        self.last_obs = obs
        return obs, reward, terminated, truncated, info


def make_env(render_mode="rgb_array"):
    env = gym.make("MiniGrid-FourRooms-v0", render_mode=render_mode)
    env = RewardWrapper(env)
    env = ReflectionWrapper(env)
    return env


def make_state(map_id, obs):
    return (map_id, state_to_symbolic(obs))


