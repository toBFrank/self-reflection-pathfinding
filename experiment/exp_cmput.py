class ReflectionWrapper(gym.Wrapper):
    def __init__(self, env):
        super().__init__(env)
        self.last_obs = None
        self.reflections = 0

    def reset(self, **kwargs):
        obs, info = self.env.reset(**kwargs)
        self.last_obs = obs
        self.reflections = 0
        return obs, info

    def step(self, action):
        if action == A_REFLECT and self.reflections >= MAX_REFLECTIONS:
            obs = self.last_obs
            reward = OVER_REFLECT_PENALTY
            terminated = False
            truncated = True
            info = {"reflected": True, "max_reflections": True}
            return obs, reward, terminated, truncated, info

        if action == A_REFLECT:
            self.reflections += 1
            obs = self.last_obs
            reward = REFLECT_COST
            terminated = False
            truncated = False
            info = {"reflected": True}
            return obs, reward, terminated, truncated, info

        obs, reward, terminated, truncated, info = self.env.step(action)
        if info is None:
            info = {}
        info["reflected"] = False
        self.last_obs = obs
        return obs, reward, terminated, truncated, info


